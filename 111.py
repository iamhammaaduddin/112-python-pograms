# Heart shape made with a loop over each row
rows = [
    "  * * *     * * *  ",
    "* * * * * * * * * *",
    "* * * * * * * * * *",
    "  * * * * * * * *  ",
    "    * * * * * *    ",
    "      * * * *      ",
    "        * *        ",
]

for line in rows:
    print(line)
